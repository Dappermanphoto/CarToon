package com.example.cartoon

import java.text.DateFormat
import java.util.Date

/** The six readiness tests a smog check cares about, each Ready, Not ready or N/A (the car doesn't have it). */
enum class Readiness(val label: String) { READY("Ready"), NOT_READY("Not ready"), NA("N/A") }

object SmogBadges {
    private val KEYS = listOf(
        "Catalyst" to listOf("Catalyst", "Heated catalyst"),
        "EVAP" to listOf("Evaporative system"),
        "O2 sensor" to listOf("Oxygen sensor"),
        "O2 heater" to listOf("Oxygen sensor heater"),
        "EGR" to listOf("EGR system"),
        "Misfire" to listOf("Misfire"),
    )

    fun of(m: MonitorStatus): List<Pair<String, Readiness>> = KEYS.map { (label, names) ->
        val found = m.monitors.filter { it.name in names }
        label to when {
            found.isEmpty() -> Readiness.NA
            found.all { it.ready } -> Readiness.READY
            else -> Readiness.NOT_READY
        }
    }
}

/** One plain-text report of codes, freeze frame and smog readiness, for sharing with a mechanic. */
object HealthReport {
    fun build(obd: ObdManager, metric: Boolean, vehicleName: String): String {
        val sb = StringBuilder()
        val vehicle = if (obd.inDemo) obd.demoName else vehicleName
        sb.append("CarToon vehicle report\n")
        sb.append(DateFormat.getDateTimeInstance(DateFormat.MEDIUM, DateFormat.SHORT).format(Date())).append('\n')
        if (vehicle.isNotBlank()) sb.append("Vehicle: ").append(vehicle).append('\n')
        obd.vin?.let { sb.append("VIN: ").append(it).append('\n') }
        if (obd.inDemo) sb.append("(demo data)\n")
        sb.append('\n')

        fun codes(title: String, list: List<String>?) {
            sb.append(title).append('\n')
            when {
                list == null -> sb.append("  Not read\n")
                list.isEmpty() -> sb.append("  None\n")
                else -> list.forEach {
                    val d = DtcDescriptions.describe(it)
                    sb.append("  ").append(it).append(" - ").append(d.title).append('\n')
                    sb.append("      ").append(d.advice).append('\n')
                }
            }
            sb.append('\n')
        }
        codes("Stored codes", obd.storedCodes)
        codes("Pending codes", obd.pendingCodes)
        codes("Permanent codes", obd.permanentCodes)

        obd.freezeFrame?.let { ff ->
            sb.append("Freeze frame")
            obd.freezeCode?.let { sb.append(" (").append(it).append(')') }
            sb.append('\n')
            ff.forEach { (key, v) ->
                val pid = ObdPids[key] ?: return@forEach
                sb.append("  ").append(pid.name).append(": ")
                    .append("%.${pid.decimals}f".format(pid.value(v, metric))).append(' ').append(pid.unitFor(metric)).append('\n')
            }
            sb.append('\n')
        }

        obd.monitors?.let { m ->
            sb.append("Smog readiness: ")
            sb.append(
                when {
                    m.milOn -> "NOT READY (check-engine light on)"
                    m.incomplete.isEmpty() -> "Ready"
                    else -> "${m.incomplete.size} test(s) not finished"
                }
            ).append('\n')
            SmogBadges.of(m).forEach { (label, r) -> sb.append("  ").append(label).append(": ").append(r.label).append('\n') }
        }
        sb.append("\nGenerated by CarToon. Codes are a starting point, not a diagnosis.\n")
        return sb.toString()
    }
}
